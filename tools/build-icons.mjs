// Regenerates public_html/assets/js/ui/icons-data.js from lucide-static SVGs.
// Usage: node tools/build-icons.mjs <path-to>/node_modules/lucide-static/icons
// Add names to ICONS below, then re-run. Lucide is ISC licensed (see assets/vendor/lucide/LICENSE).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS = `layout-dashboard wrench clipboard-list package boxes warehouse truck users user user-cog receipt
indian-rupee wallet chart-column settings bell search plus pencil trash-2 x check chevron-down chevron-right
chevron-left chevron-up menu log-out languages sun moon qr-code printer download upload share-2 phone
message-circle filter arrow-up-down arrow-left eye eye-off triangle-alert info circle-check circle-x clock
calendar map-pin layers tag scan-line refresh-cw ellipsis minus history list-checks camera image file-text
send bike hammer shopping-cart credit-card banknote hand-coins badge-percent shield-check key-round lock
package-search package-plus inbox circle-alert external-link copy store gauge fuel square-check
panel-left-close panel-left-open command arrow-right undo-2 ban link circle-dot loader-circle hourglass
party-popper sparkles chart-line monitor file-spreadsheet house circle-user`.split(/\s+/).filter(Boolean);

const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/build-icons.mjs <lucide-static/icons dir>');
  process.exit(1);
}
const out = {};
for (const name of ICONS) {
  const svg = readFileSync(join(src, `${name}.svg`), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  out[name] = inner;
}
const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, '..', 'public_html', 'assets', 'js', 'ui', 'icons-data.js');
writeFileSync(target, `// Generated by tools/build-icons.mjs from lucide-static (ISC). Do not edit.\nexport const ICONS = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};\n`);
console.log(`Wrote ${Object.keys(out).length} icons to ${target}`);
